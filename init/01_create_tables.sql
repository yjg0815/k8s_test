-- gvenzl/oracle-free 컨테이너 최초 기동 시 SYS로 자동 실행됨
-- APP_USER(DEMOUSER)는 이미 FREEPDB1에 생성되어 있는 상태 (compose의 APP_USER/APP_USER_PASSWORD)

ALTER SESSION SET CONTAINER = FREEPDB1;
ALTER SESSION SET CURRENT_SCHEMA = DEMOUSER;

CREATE TABLE ORDER_TB (
    ORDER_ID       VARCHAR2(20)  NOT NULL,
    APPLICANT_KEY  VARCHAR2(50)  NOT NULL,
    USER_ID        VARCHAR2(50),
    NAME           VARCHAR2(100),
    ADDRESS        VARCHAR2(300),
    ITEM_ID        VARCHAR2(50),
    ITEM_NAME      VARCHAR2(100),
    PRICE          VARCHAR2(20),
    STATUS         VARCHAR2(10),
    CONSTRAINT PK_ORDER_TB PRIMARY KEY (ORDER_ID, APPLICANT_KEY)
);

CREATE TABLE SHIPMENT_TB (
    SHIPMENT_ID    VARCHAR2(20)  NOT NULL,
    APPLICANT_KEY  VARCHAR2(50)  NOT NULL,
    ORDER_ID       VARCHAR2(20),
    ITEM_ID        VARCHAR2(50),
    ADDRESS        VARCHAR2(300),
    CONSTRAINT PK_SHIPMENT_TB PRIMARY KEY (SHIPMENT_ID, APPLICANT_KEY)
);
